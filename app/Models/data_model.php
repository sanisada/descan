   public function getAll()
   {
      $builder = $this->db->table('data dt');
      $builder->join('desa ds', 'ds.kode_desa = dt.R104');
      $builder->join('kec k', 'k.kode_kec = dt.R103');
      $query = $builder->get();
      return $query->getResult();
   }

   public function getDataByDesa($desa_id)
   {
      $builder = $this->db->table('data dt');
      $builder->join('desa ds', 'ds.kode_desa = dt.R104');
      $builder->join('kec k', 'k.kode_kec = dt.R103');
